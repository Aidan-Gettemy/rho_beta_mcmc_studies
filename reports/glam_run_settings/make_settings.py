"""Writes glam_run_settings.md: every GLAM setting of the runs r12, r24, r24m, r24m2, read from the sbatch scripts (run from the repo root:
python reports/glam_run_settings/make_settings.py).  r24 is shown as continued (the sbatch of the first job had n_iter 20000, window2 4000)."""
import os, re
S = "cluster/slurm"
RUNS = [("r12", "glam_r12.sbatch"), ("r24", "glam_r24_cont.sbatch"), ("r24m", "glam_r24m.sbatch"), ("r24m2", "glam_r24m2.sbatch")]

def read(fn):
    t = open(os.path.join(S, fn)).read()
    blk = re.search(r"^GLAM_FLAGS=\(\n(.*?)^\)", t, re.M | re.S).group(1)
    fl, sec, cur = {}, {}, "General"
    for l in blk.splitlines():
        m = re.match(r"\s*# --- (.*?)(?:\s*\(|:|$)", l)
        if m: cur = m.group(1).strip()
        l = l.split("#")[0].strip()
        if l.startswith("--"):
            p = l.split(None, 1); fl[p[0]] = p[1] if len(p) > 1 else ""; sec[p[0]] = cur
    sb = {}
    for k in ("ntasks", "mem", "partition", "time"):
        sb[k] = re.search(rf"^#SBATCH --{k}=(\S+)", t, re.M).group(1)
    sb["sigmas"] = f"{fl['--sigma-conc']} / {fl['--sigma-dp']}"
    return fl, sec, sb

data = {r: read(f) for r, f in RUNS}
names = [r for r, _ in RUNS]
order = list(data["r24m2"][0])
for r in names:
    for k in data[r][0]:
        if k not in order: order.append(k)
sec = {}
for r in names: sec.update(data[r][1])
out = ["# GLAM run settings: r12, r24, r24m, r24m2", "",
       "Generated by `reports/glam_run_settings/make_settings.py` from `cluster/slurm/glam_{r12,r24_cont,r24m,r24m2}.sbatch`; "
       "regenerate after editing a script. Rows marked **◆** differ between runs.", "",
       "| run | what it is |", "|---|---|",
       "| r12 | 12 chains, one anchor (best state), sigma 0.001 / 0.002, window1 8000 (first real GLAM run on the offline beta(rho) curve) |",
       "| r24 | 24 chains, one anchor, sigma doubled, window1 14000; shown as continued to 40000 iterations (the first job had n_iter 20000, window2 4000; `glam_r24_cont.sbatch` resumed it) |",
       "| r24m | r24 with an open multi-anchor archive from scratch: no cap, no minimum distance, roles 25 % exploit / 25 % frontier / 50 % explore |",
       "| r24m2 | r24m with a selective archive (minimum distance 3, score cut-off 0.5, log-det gain scale 10), quality tolerance 100 and restart radii doubled |", "",
       "## Resources", "", "| | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
for k, lab in (("ntasks", "chains (MPI tasks)"), ("partition", "partition"), ("mem", "memory"), ("time", "time limit of one job"), ("sigmas", "sigma_conc / sigma_dp")):
    out.append(f"| {lab} | " + " | ".join(data[r][2][k] for r in names) + " |")
diff = [k for k in order if len({data[r][0].get(k, "—") for r in names}) > 1]
def table(keys):
    rows = ["| flag | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for k in keys:
        v = [data[r][0].get(k, "—") for r in names]
        rows.append(f"| {'◆ ' if k in diff else ''}`{k}` | " + " | ".join(v) + " |")
    return rows
out += ["", "## Settings that differ between the runs", ""] + table(diff)
out += ["", "## All settings, by group", ""]
groups = []
for k in order:
    if sec[k] not in groups: groups.append(sec[k])
for g in groups:
    out += [f"### {g}", ""] + table([k for k in order if sec[k] == g]) + [""]
open("reports/glam_run_settings/glam_run_settings.md", "w").write("\n".join(out) + "\n")
print(len(order), "flags;", len(diff), "differ")
