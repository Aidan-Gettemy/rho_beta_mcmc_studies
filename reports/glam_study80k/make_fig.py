"""Figures and LaTeX tables of the s80k report, straight from the returned tables (runs/cluster/tables/e6_glam_s80k_*).

    python reports/glam_study80k/make_fig.py            # from the repo root

Writes fig_calibration.png, tables_auto.tex and copies the core figures of each arm next to the report.
"""
import json
import os
import shutil

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TAB = os.path.join(ROOT, "runs", "cluster", "tables")
FIG = os.path.join(ROOT, "runs", "cluster", "figures")
ARMS = [("1", "pCN", "s80k_pcn", "#2a78d6", "o"), ("2", "one anchor", "s80k_glam1", "#eb6834", "s"),
        ("2b", "one anchor + memory", "s80k_glam1_best", "#1baf7a", "^"), ("3", "many anchors", "s80k_glamN", "#eda100", "D"),
        ("4", "one anchor + mask", "s80k_glam1_mask", "#e87ba4", "v"), ("5", "many anchors + mask", "s80k_glamN_mask", "#008300", "P")]


def load(tag):
    d = os.path.join(TAB, f"e6_glam_{tag}")
    m = json.load(open(os.path.join(d, "mpsrf.json")))
    f = json.load(open(os.path.join(d, "field_comparison.json")))
    g = json.load(open(os.path.join(d, "diagnostics.json")))
    return m, f, g


rows = []
for a, name, tag, col, mk in ARMS:
    m, f, g = load(tag)
    c, p, po = m["curves"], m["psrf_final"], f["posterior"]
    rows.append(dict(arm=a, name=name, tag=tag, col=col, mk=mk, n=len(m["chains"]), rho=c["rho (w)"]["final_mpsrf"],
                     f100=c["first 100"]["final_mpsrf"], b0=c["block 0"]["final_mpsrf"], cf100=c["first 100"]["convergence_iteration"],
                     pmax=p["max"], pmed=p["median"], below=p["frac_below_1p1"], rmse=f["mean"]["rmse"], corr=f["mean"]["corr"],
                     cov1=po["coverage_1sd"], cov2=po["coverage_2sd"], rmsz=po["rms_z"], sd=po["mean_std"],
                     acc=g["acceptance"]["global"]["mean"], rec=g["re"]["conc"]["mean"]))

# ---------------------------------------------------------------------------------------------------- figure
INK, MUTED, SURF = "#0b0b0b", "#52514e", "#fcfcfb"
plt.rcParams.update({"font.size": 10, "axes.facecolor": SURF, "figure.facecolor": SURF, "axes.edgecolor": MUTED, "text.color": INK,
                     "axes.labelcolor": INK, "xtick.color": MUTED, "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False})
fig, ax = plt.subplots(1, 2, figsize=(11, 4.3))
a0 = ax[0]
off = {"1": (9, 5), "2": (8, -12), "2b": (8, 2), "3": (8, 4), "4": (-8, -15), "5": (-8, 7)}
for r in rows:
    a0.scatter(r["pmax"], r["cov2"], s=70, color=r["col"], marker=r["mk"], edgecolor=SURF, linewidth=1.2, zorder=3)
    dx, dy = off[r["arm"]]
    a0.annotate(f"{r['arm']} {r['name']}", (r["pmax"], r["cov2"]), textcoords="offset points", xytext=(dx, dy), fontsize=9, color=INK,
                ha="left" if dx > 0 else "right")
a0.axhline(0.95, color=MUTED, ls="--", lw=0.9)
a0.text(1.45, 0.965, "ideal 2$\\sigma$ coverage 0.95", fontsize=8.5, color=MUTED, va="bottom")
a0.axvline(1.1, color=MUTED, ls=":", lw=0.9)
a0.text(1.105, 0.03, "PSRF 1.1", fontsize=8.5, color=MUTED)
a0.set_xscale("log"); a0.set_xlim(0.97, 4.5); a0.set_ylim(0, 1.05)
a0.set_xticks([1, 1.5, 2, 3, 4]); a0.set_xticklabels(["1", "1.5", "2", "3", "4"])
a0.set_xlabel("max PSRF over the 6001 coordinates (log scale)"); a0.set_ylabel("2$\\sigma$ coverage of the reference field")
a0.set_title("Chains that agree are not a calibrated posterior", loc="left", fontsize=10.5)
a0.grid(color="#e4e3df", lw=0.6, zorder=0)
a1 = ax[1]
ys = list(range(len(rows)))[::-1]
for y, r in zip(ys, rows):
    a1.hlines(y, 1.0, r["rmsz"], color=r["col"], lw=1.6, zorder=2)
    a1.scatter(r["rmsz"], y, s=70, color=r["col"], marker=r["mk"], edgecolor=SURF, linewidth=1.2, zorder=3)
    a1.text(r["rmsz"] + 0.12, y, f"{r['rmsz']:.2f}", va="center", fontsize=9, color=INK)
a1.axvline(1.0, color=MUTED, ls="--", lw=0.9)
a1.text(1.04, -0.45, "ideal 1", fontsize=8.5, color=MUTED, va="center")
a1.set_yticks(ys); a1.set_yticklabels([f"{r['arm']} {r['name']}" for r in rows])
a1.set_xlim(0.8, 6.4); a1.set_ylim(-0.7, len(rows) - 0.4); a1.set_xlabel("rms $z$-score of the reference field under the posterior")
a1.set_title("Over-confidence (rms $z$ above 1)", loc="left", fontsize=10.5)
a1.grid(axis="x", color="#e4e3df", lw=0.6, zorder=0)
fig.tight_layout()
fig.savefig(os.path.join(HERE, "fig_calibration.png"), dpi=200)

# ---------------------------------------------------------------------------------------------------- tables
f2 = lambda v: f"{v:.3f}"  # noqa: E731
with open(os.path.join(HERE, "tables_auto.tex"), "w") as fh:
    fh.write("% generated by make_fig.py from tables/e6_glam_s80k_*/{mpsrf,field_comparison,diagnostics}.json: do not edit by hand\n")
    fh.write("\\begin{tabular}{llrrrrrr}\\toprule\n")
    fh.write("arm & & MPSRF $\\rho$ & MPSRF first 100 & MPSRF block 0 & PSRF max & PSRF median & coords $<1.1$ \\\\ \\midrule\n")
    for r in rows:
        fh.write(f"{r['arm']} & {r['name']} & {f2(r['rho'])} & {f2(r['f100'])} & {r['b0']:.2f} & {f2(r['pmax'])} & {f2(r['pmed'])} & {r['below']:.2f} \\\\\n")
    fh.write("\\bottomrule\\end{tabular}\n")
with open(os.path.join(HERE, "tables_auto_cal.tex"), "w") as fh:
    fh.write("% generated by make_fig.py: do not edit by hand\n")
    fh.write("\\begin{tabular}{llrrrrrr}\\toprule\n")
    fh.write("arm & & RMSE of mean & corr.\\ of mean & coverage 1$\\sigma$ & coverage 2$\\sigma$ & rms $z$ & mean sd \\\\ \\midrule\n")
    for r in rows:
        fh.write(f"{r['arm']} & {r['name']} & {f2(r['rmse'])} & {f2(r['corr'])} & {f2(r['cov1'])} & {f2(r['cov2'])} & {r['rmsz']:.2f} & {f2(r['sd'])} \\\\\n")
    fh.write("\\bottomrule\\end{tabular}\n")

# ---------------------------------------------------------------------------------------------------- copy the figures
for r in rows:
    src = os.path.join(FIG, f"e6_glam_{r['tag']}")
    shutil.copy(os.path.join(src, "small", "traces_phi.png"), os.path.join(HERE, f"fig_phi_{r['arm']}.png"))
    shutil.copy(os.path.join(src, "fields", "small", "logperm_layers_std.png"), os.path.join(HERE, f"fig_std_{r['arm']}.png"))
shutil.copy(os.path.join(FIG, "e6_glam_s80k_pcn", "coef_variance_by_index.png"), os.path.join(HERE, "fig_stage0_24.png"))
shutil.copy(os.path.join(FIG, "e6_glam_s80k_pcn", "coef_variance_by_index_12chains.png"), os.path.join(HERE, "fig_stage0_12.png"))
print("done:", HERE)
